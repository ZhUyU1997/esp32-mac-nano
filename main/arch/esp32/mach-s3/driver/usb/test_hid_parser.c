static void test_read_bits(void)
{
	printf("--- read_bits ---\n");
	struct hid_field f = {.report_count = 1, .logical_minimum = 0};
	uint8_t buf[] = {0x01, 0x03};

	f.report_size = 9; expect(hid_field_extract(&f, buf, 2, 0) == 0x101, "off=0 sz=9 want 0x101\n");
	f.report_size = 8; expect(hid_field_extract(&f, buf, 2, 0) == 0x01,  "off=0 sz=8 want 0x01\n");
	f.report_offset = 1; f.report_size = 7;
	expect(hid_field_extract(&f, buf, 2, 0) == 0, "off=1 sz=7 want 0\n");
	f.report_offset = 0; f.report_size = 16;
	expect(hid_field_extract(&f, buf, 2, 0) == 0x301, "off=0 sz=16 want 0x301\n");
	f.report_offset = 1; f.report_size = 8;
	expect(hid_field_extract(&f, buf, 2, 0) == 0x80,  "off=1 sz=8 want 0x80\n");
	uint8_t buf2[] = {0x54, 0x01};
	f.report_offset = 0; f.report_size = 10;
	expect(hid_field_extract(&f, buf2, 2, 0) == 0x154, "off=0 sz=10 want 0x154\n");
}

static void test_mouse_buttons(void)
{
	printf("--- mouse: buttons ---\n");
	struct hid_device *h = hid_parse_device(desc_mouse_complex, sizeof(desc_mouse_complex));
	if (!h) { printf("FAIL: parse\n"); failures++; return; }
	uint8_t d[] = {0x05,0,0,0,0,0,0,0};
	struct hid_field *f;
	f = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x09, 1); expect(f && hid_field_extract(f,d,8,0)==1, "btn1\n");
	f = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x09, 2); expect(f && hid_field_extract(f,d,8,0)==0, "btn2\n");
	f = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x09, 3); expect(f && hid_field_extract(f,d,8,0)==1, "btn3\n");
	hid_destroy_device(h);
}

static void test_mouse_movement(void)
{
	printf("--- mouse: 16-bit XY + wheel ---\n");
	struct hid_device *h = hid_parse_device(desc_mouse_complex, sizeof(desc_mouse_complex));
	if (!h) { printf("FAIL: parse\n"); failures++; return; }
	uint8_t d[] = {0,0,0,1,0x64,0,0xCE,0xFF};
	struct hid_field *fx = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x01, 0x30);
	struct hid_field *fy = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x01, 0x31);
	struct hid_field *fw = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x01, 0x38);
	expect(fx && hid_field_extract(fx,d,8,0)==100, "X\n");
	expect(fy && hid_field_extract(fy,d,8,0)==-50, "Y\n");
	expect(fw && hid_field_extract(fw,d,8,0)==1,   "wheel\n");
	hid_destroy_device(h);
}

static void test_keyboard_modifiers(void)
{
	printf("--- keyboard: modifiers ---\n");
	struct hid_device *h = hid_parse_device(desc_keyboard, sizeof(desc_keyboard));
	if (!h) { printf("FAIL: parse\n"); failures++; return; }
	/* LeftCtrl(bit0)+LeftShift(bit1)=0x03 */
	uint8_t d[] = {0x03,0,0,0,0,0,0,0};
	struct hid_field *f;
	f = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x07, 0xe0);
	expect(f && hid_field_extract(f,d,8,0)==1, "LCtrl\n");
	f = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x07, 0xe1);
	expect(f && hid_field_extract(f,d,8,0)==1, "LShift\n");
	f = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x07, 0xe2);
	expect(f && hid_field_extract(f,d,8,0)==0, "LAlt\n");
	hid_destroy_device(h);
}

static void test_keyboard_keys(void)
{
	printf("--- keyboard: keys ---\n");
	struct hid_device *h = hid_parse_device(desc_keyboard, sizeof(desc_keyboard));
	if (!h) { printf("FAIL: parse\n"); failures++; return; }
	/* Keyboard has 8 modifier fields + 1 const + 6 key array = 15 input fields.
	 * Verify parsing succeeds and field count is reasonable. */
	unsigned n = 0;
	for (unsigned i = 0; i < HID_MAX_IDS; i++) {
		struct hid_report *r = h->report_enum[0]
			? h->report_enum[0]->report_id_hash[i] : NULL;
		if (r) n += r->maxfield;
	}
	expect(n >= 14, "kbd fields %u < 14\n", n);
	hid_destroy_device(h);
}

