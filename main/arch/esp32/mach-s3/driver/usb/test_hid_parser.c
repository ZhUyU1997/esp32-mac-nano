static void test_ps4_hatswitch(void)
{
	printf("--- ps4: hatswitch ---\n");
	struct hid_device *h = hid_parse_device(desc_ps4, sizeof(desc_ps4));
	if (!h) { printf("FAIL: parse\n"); failures++; return; }
	/* Skip Report ID byte */
	uint8_t d[] = {0x82,0x7a,0x82,0x80,0x00,0};
	struct hid_field *f = hid_find_field(h, HID_REPORT_TYPE_INPUT, 0x01, 0x39);
	expect(f != NULL, "hatswitch field\n");
	if (f) expect(hid_field_extract(f, d, 6, 0) == 0, "hat UP\n");
	hid_destroy_device(h);
}

static void test_descriptors(void)
{
	printf("--- descriptors ---\n");
#define CHECK(p,pg,id) do { \
	struct hid_device *h = hid_parse_device(p, sizeof(p)); \
	expect(h != NULL, "parse %s\n", #p); \
	if (h) { expect(hid_find_field(h,HID_REPORT_TYPE_INPUT,pg,id)!=NULL, "%s field 0x%04x\n",#p,id); hid_destroy_device(h); } \
} while (0)

	CHECK(desc_mouse_simple, 0x01, 0x30);
	CHECK(desc_gamepad, 0x01, 0x30);
	CHECK(desc_keyboard, 0x07, 0xe0);
	CHECK(desc_xbox360, 0x01, 0x30);
	CHECK(desc_ps4, 0x01, 0x30);
}

int test_hid_parser(void)
{
	printf("=== HID Report Parser Tests ===\n");
	failures = 0;

	test_read_bits();
	test_mouse_buttons();
	test_mouse_movement();
	test_keyboard_modifiers();
	test_keyboard_keys();
	test_xbox360_button();
	test_ps4_button();
	test_ps4_hatswitch();
	test_descriptors();

	printf("%s: %d failures\n", failures ? "FAIL" : "PASS", failures);
	return failures;
}

int main(void) { return test_hid_parser(); }
