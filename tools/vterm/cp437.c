/* cp437.c — CP437 (IBM PC code page 437) byte -> Unicode conversion.
 *
 * Table generated from Python's cp437 codec (authoritative). The renderer
 * maps the resulting code points back to the VGA glyph indices via
 * term_unicode_to_cp437, so an art byte round-trips exactly.
 */
#include <stddef.h>
#include <stdint.h>

#include "cp437.h"

